// Generates skills/nortezh/ from src/prompts.ts.
//
// The skill exists because an MCP prompt is user-invoked only: the model has no
// `prompts/get`, so a plain "deploy this to nortezh" loads none of it. A skill's frontmatter
// description sits in the model's context permanently, so the model pulls the guidance
// itself — and, critically, it lands BEFORE the agent starts running Bash. That matters
// because `docker build` and reading a credential store never touch an MCP tool at all, so
// nothing inside the server can see them.
//
// Three files rather than one, so cost is graduated:
//
//   SKILL.md         always, once the skill fires        ~2k
//   resources.md     any Nortezh work                    ~4k
//   deploy-stack.md  only when creating or changing     ~15k
//
// The procedure is rendered WITHOUT the resource model inlined — unlike the prompt, which
// has to inline it. Here they are sibling files that can reference each other.

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { renderDeployStackForSkill, RESOURCE_MODEL_TEXT } from '../src/prompts.js'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const out = resolve(root, 'skills/nortezh')

const GENERATED = '<!-- GENERATED by scripts/generate-skill.ts from src/prompts.ts — do not edit by hand. -->'

/**
 * The frontmatter description is the entire trigger surface — the only part of the skill
 * that is always in context, and what the model decides from.
 *
 * Deliberately fires on ANY Nortezh work, not just deploys: the resource model is what stops
 * a read-only answer being wrong (readiness differs per resource, only deployments and
 * domains can fail), and it is cheap. The expensive procedure is a second, conditional read.
 */
const SKILL = `---
name: nortezh
description: Use whenever the user mentions Nortezh — deploying, inspecting or changing anything on the Nortezh platform (projects, deployments, databases, disks, domains, routes, env groups, pull secrets), reading its state, or asking how it works. Read resources.md for any Nortezh work; also read deploy-stack.md before creating, changing or deleting anything.
---

${GENERATED}

# Nortezh

Work on the Nortezh PaaS through the \`nortezh\` MCP tools.

## Read these, in this order

1. **[resources.md](./resources.md) — always, before answering anything about Nortezh.**
   What each resource is, what it depends on, how you know it is ready, what can still be
   changed. Readiness is reported differently by nearly every resource, and only deployments
   and domains can report failure at all, so an answer given without this is usually wrong in
   a way that looks right.

2. **[deploy-stack.md](./deploy-stack.md) — additionally, before anything is created,
   changed or deleted.** The seven-step procedure, the plan template, and the approval gate.
   Read it *before* you start, not after the first call fails.

A read-only question — "what is deployed?", "show me metrics" — needs only the first.

## These hold whether or not you read further

⚠️ **Never build or push a container image.** Not \`docker build\`, not \`docker push\`, not a
Makefile target that wraps one. CI builds and pushes; the deployment is created pointing at
the tag CI will push and **fails until CI runs, on purpose**. A laptop build is unreviewed
and unreproducible, and pushing it needs a write credential that does not belong in this
conversation.

⚠️ **Never obtain, read or ask for a credential.** Not from the user ("paste your token"),
not from the machine (\`gh auth token\`, \`~/.docker/config.json\`, the keychain, a \`.env\`).
The user creates every credential themselves — pull secret in the console, registry key in
GitHub Secrets — and tells you only its **name**. Reading the repo is fine; reading credential
stores is not. The line is whether the file is checked in.

⚠️ **Nothing is created, changed or deleted before the user approves a written plan.**
Inventory and reads come first, then a plan, then explicit approval. See deploy-stack.md.

⚠️ **Never resolve a blocked step by weakening something else.** "I cannot create a pull
secret, so let's make the image public" trades a console step for permanently publishing the
application image. When a step is blocked, hand it to the user.
`

const RESOURCES = `${GENERATED}

${RESOURCE_MODEL_TEXT}
`

const DEPLOY_STACK = `${GENERATED}

${renderDeployStackForSkill()}
`

mkdirSync(out, { recursive: true })
writeFileSync(resolve(out, 'SKILL.md'), SKILL)
writeFileSync(resolve(out, 'resources.md'), RESOURCES)
writeFileSync(resolve(out, 'deploy-stack.md'), DEPLOY_STACK)

const k = (text: string) => `${Math.round(text.length / 4000)}k`
console.log(
  `generate-skill: skills/nortezh/ — SKILL.md ~${k(SKILL)}, ` +
    `resources.md ~${k(RESOURCES)}, deploy-stack.md ~${k(DEPLOY_STACK)} tokens`,
)
