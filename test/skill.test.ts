// The skill is the only mechanism that reaches the model BEFORE it starts running Bash.
//
// Everything else here is downstream of an MCP call: a prompt is user-invoked, a tool is
// model-invoked, and both arrive after the agent has already decided what to do. But
// `docker build` and reading a credential store never touch an MCP tool at all — so the
// failure that started this (an image built on a laptop and pushed with the keychain
// credential) is invisible to the server. The skill's frontmatter sits in context from the
// first token of the turn, which is the only place that can catch it.

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'

import { PROMPTS, RESOURCE_MODEL_TEXT, renderDeployStackForSkill } from '../src/prompts.js'

const dir = resolve(dirname(fileURLToPath(import.meta.url)), '../skills/nortezh')
const read = (name: string) => readFileSync(join(dir, name), 'utf8')

const skill = read('SKILL.md')
const resources = read('resources.md')
const deployStack = read('deploy-stack.md')

test('the frontmatter fires on any Nortezh work, not only deploys', () => {
  // The description is the entire trigger surface. Scoping it to deploys would leave every
  // read-only answer ungoverned — and readiness differs per resource, so those answers are
  // exactly where a confident wrong answer comes from.
  assert.match(skill, /^---\nname: nortezh\ndescription: /)
  assert.match(skill, /Use whenever the user mentions Nortezh/)
  assert.match(skill, /deploying, inspecting or changing/)
  // And it must say which file to read when, or the tiering does not happen.
  assert.match(skill, /Read resources\.md for any Nortezh work/)
  assert.match(skill, /also read deploy-stack\.md before creating, changing or deleting/)
})

test('the invariants survive even if no sibling file is read', () => {
  // SKILL.md is the only part guaranteed to be in context once the skill fires. The rules
  // that cannot be missed have to be in it, not only in the 15k procedure.
  // Flattened: the source wraps at 90 columns, so a rule can straddle a line break.
  const flat = skill.replace(/\s+/g, ' ')
  assert.match(flat, /Never build or push a container image/)
  assert.match(flat, /Never obtain, read or ask for a credential/)
  assert.match(flat, /Nothing is created, changed or deleted before the user approves/)
  assert.match(flat, /Never resolve a blocked step by weakening something else/)
  // The shell-specific ones, since this is the only surface that reaches them.
  assert.match(flat, /`gh auth token`, `~\/\.docker\/config\.json`/)
  assert.match(flat, /not a Makefile target that wraps one/)
})

test('cost is graduated — the point of three files', () => {
  // ~1k for a mention, ~5k for a question, ~20k only when deploying. One file would load
  // everything for "how much does a disk cost?".
  assert.ok(skill.length < 4_500, `SKILL.md is ${skill.length} chars — too big to load always`)
  assert.ok(resources.length > 10_000, 'resources.md should carry the whole model')
  assert.ok(deployStack.length > 40_000, 'deploy-stack.md should carry the whole procedure')
})

test('the resource model is referenced by deploy-stack, not duplicated into it', () => {
  // The MCP prompt has to inline it — a prompt cannot fetch another prompt. Skill files can
  // reference each other, and duplicating would both double the cost and give the next edit
  // two places to drift apart.
  assert.equal(
    deployStack.includes('Reference: what each Nortezh resource is'),
    false,
    'the model is inlined into deploy-stack.md',
  )
  assert.match(deployStack, /The resource model lives in \[resources\.md\]\(\.\/resources\.md\)/)
})

test('the skill and the prompts are one procedure', () => {
  // Same source, so a rule fixed in prompts.ts reaches both. If these diverge, a user who
  // typed the slash command and a model that read the skill are following different rules.
  assert.ok(resources.includes(RESOURCE_MODEL_TEXT), 'resources.md is not the model verbatim')
  assert.ok(deployStack.includes(renderDeployStackForSkill()), 'deploy-stack.md is not the render')

  const promptModel = PROMPTS.find((p) => p.name === 'resources')?.render({})
  assert.equal(promptModel, RESOURCE_MODEL_TEXT, 'the prompt and the skill differ on the model')
})

test('generated files say so', () => {
  // They are committed, so someone will otherwise edit one by hand and lose it on the next
  // build.
  for (const [name, text] of [
    ['SKILL.md', skill],
    ['resources.md', resources],
    ['deploy-stack.md', deployStack],
  ] as const) {
    assert.match(text, /GENERATED by scripts\/generate-skill\.ts/, `${name} lacks the banner`)
  }
})
